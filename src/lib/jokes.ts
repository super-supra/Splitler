/** Whole local days since 1970, so the joke flips at the viewer's midnight. */
export function dayNumber(d = new Date()): number {
  return Math.floor((d.getTime() - d.getTimezoneOffset() * 60_000) / 86_400_000)
}

export function jokeFor(d = new Date()): [string, string] {
  return JOKES[dayNumber(d) % JOKES.length]
}
